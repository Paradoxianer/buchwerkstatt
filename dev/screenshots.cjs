// Klickt die Vorschau durch und macht Screenshots (für die Entwicklung).
const { chromium } = require('playwright');
const path = require('path');
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 300, height: 760 }, deviceScaleFactor: 2 });
  const fehler = [];
  page.on('pageerror', e => fehler.push(String(e)));
  page.on('console', m => { if (m.type() === 'error') fehler.push(m.text()); });
  const url = 'file://' + path.resolve(__dirname, '../dist/vorschau.html') + (process.argv[2] || '');
  await page.goto(url);
  await page.waitForTimeout(1200);
  const bild = async (n) => page.screenshot({ path: path.resolve(__dirname, 'screenshots', n + '.png') });
  await bild('1-notizen');
  await page.fill('#neu', 'Person Kowal');
  await page.waitForTimeout(200);
  await bild('2-eingabe-vorschau');
  await page.fill('#neu', '');
  await page.type('#neu', 'Lena sieht @Hei');
  await page.waitForTimeout(200);
  await bild('3-at-vorschlag');
  await page.keyboard.press('Enter');
  await page.type('#neu', 'zum ersten Mal weinen.');
  await page.keyboard.press('Enter');
  await page.waitForTimeout(600);
  await bild('4-gespeichert');
  await page.click('[data-filter="hier"]');
  await page.waitForTimeout(800);
  await bild('5-hier');
  await page.click('#leiste [data-nav="welt"]');
  await page.waitForTimeout(300);
  await bild('6-welt');
  await page.click('.zeile[data-id="p1"]');
  await page.waitForTimeout(300);
  await bild('7-karte');
  await page.click('[data-aktion="ki-felder"]');
  await page.waitForTimeout(400);
  await bild('8-ki-ohne-key');
  await page.click('[data-toast="aktion"]');
  await page.waitForTimeout(300);
  await page.fill('#ki-key', 'sk-ant-test');
  await page.click('[data-aktion="ki-key"]');
  await page.waitForTimeout(500);
  await bild('9-einstellungen');
  await page.click('#leiste [data-nav="welt"]');
  await page.click('.zeile[data-id="p1"]');
  await page.click('[data-aktion="ki-felder"]');
  await page.waitForTimeout(700);
  await bild('10-ki-vorschlag');
  await page.click('[data-aktion="ki-uebernehmen"]');
  await page.waitForTimeout(500);
  await page.click('[data-aktion="vorkommen"]');
  await page.waitForTimeout(600);
  await page.evaluate(() => document.querySelector('#ansicht').scrollTo(0, 9999));
  await bild('11-karte-unten');
  await page.click('.ref[data-id="d1"], .ref[data-id]:not([data-id="p1"])');
  await page.waitForTimeout(300);
  await bild('12-taschenuhr');
  await page.click('#leiste [data-nav="zeit"]');
  await page.waitForTimeout(300);
  await bild('13-zeit');
  await page.click('#leiste [data-nav="pinnwand"]');
  await page.waitForTimeout(300);
  await bild('14-pinnwand');
  await page.click('#leiste [data-nav="ziel"]');
  await page.waitForTimeout(700);
  await bild('15-ziel');
  await page.click('#leiste [data-nav="notizen"]');
  await page.waitForTimeout(300);
  await page.click('.ref.neu');
  await page.waitForTimeout(200);
  await bild('16-neu-anlegen');
  console.log(fehler.length ? 'FEHLER:\n' + fehler.join('\n') : 'keine JS-Fehler');
  await browser.close();
})();
